// FormatIncidentMarkdown generates a forensic security dossier in Markdown format.
func FormatIncidentMarkdown(inc *detector.Incident) string {
	var sb strings.Builder

	sb.WriteString(fmt.Sprintf("# Security Incident Dossier: %s\n\n", inc.ID))
	sb.WriteString("Generated by honeyagent Autonomous AI Threat Deception Airlock.\n\n")

	sb.WriteString("## Executive Summary\n\n")
	sb.WriteString(fmt.Sprintf("- **Incident ID**: `%s`\n", inc.ID))
	sb.WriteString(fmt.Sprintf("- **Timestamp**: %s\n", inc.Timestamp.Format(time.RFC3339)))
	sb.WriteString(fmt.Sprintf("- **Severity**: **%s**\n", strings.ToUpper(inc.Severity)))
	sb.WriteString(fmt.Sprintf("- **Threat Score**: %d / 100\n", inc.ThreatScore))
	sb.WriteString(fmt.Sprintf("- **Trigger Type**: `%s`\n", inc.TriggerType))
	sb.WriteString(fmt.Sprintf("- **Attacker IP**: `%s`\n", inc.ClientIP))
	sb.WriteString(fmt.Sprintf("- **Client User-Agent**: `%s`\n", inc.UserAgent))
	sb.WriteString(fmt.Sprintf("- **Airlock Countermeasure**: Session Quarantined & Tarpitted\n\n"))

	sb.WriteString("## MITRE ATLAS Threat Matrix Classification\n\n")
	if len(inc.MITRETechniques) > 0 {
		atlasDetails := detector.GetATLASDetails(inc.MITRETechniques)
		for _, ref := range atlasDetails {
			sb.WriteString(fmt.Sprintf("- **%s** (%s) - *%s*: %s\n", ref.ID, ref.Name, ref.Tactic, ref.Description))
		}
	} else {
		sb.WriteString("No MITRE ATLAS techniques mapped.\n")
	}
	sb.WriteString("\n")

	sb.WriteString("## Cryptographic Canary Proof\n\n")
	if inc.CanaryHit != nil && inc.CanaryHit.Payload != nil {
		sb.WriteString(fmt.Sprintf("- **Canary Document ID**: `%s`\n", inc.CanaryHit.Payload.ID))
		sb.WriteString(fmt.Sprintf("- **Target Vector Store**: `%s`\n", inc.CanaryHit.Payload.Store))
		sb.WriteString(fmt.Sprintf("- **Detection Location**: `%s`\n", inc.CanaryHit.Location))
		sb.WriteString(fmt.Sprintf("- **Cryptographic Token**: `%s`\n", inc.CanaryHit.Token))
		sb.WriteString("- **HMAC-SHA256 Signature**: **VALIDATED (100% True-Positive Signal)**\n")
	} else if inc.ToolProbe != nil {
		sb.WriteString(fmt.Sprintf("- **Decoy Administrative Tool**: `%s`\n", inc.ToolProbe.ToolName))
		sb.WriteString(fmt.Sprintf("- **Invoked Arguments**: `%v`\n", inc.ToolProbe.Arguments))
		sb.WriteString("- **Signal Verification**: **Unadvertised Function Invocated (Confirmed Adversary)**\n")
	} else if inc.OOBHit != nil {
		sb.WriteString(fmt.Sprintf("- **Out-of-Band Channel**: `%s`\n", inc.OOBHit.Channel))
		sb.WriteString(fmt.Sprintf("- **Canary Document**: `%s`\n", inc.OOBHit.Payload.ID))
		sb.WriteString(fmt.Sprintf("- **HTTP Referer**: `%s`\n", inc.OOBHit.Referer))
	}
	sb.WriteString("\n")

	sb.WriteString("## Attacker Conversational Trajectory\n\n")
	if len(inc.Trajectory) == 0 {
		sb.WriteString("No prior turns recorded. Adversarial trigger occurred on initial request.\n\n")
	} else {
		sb.WriteString("| Turn | Timestamp | Inbound Adversarial Prompt | Response Action |\n")
		sb.WriteString("|---|---|---|---|\n")
		for i, step := range inc.Trajectory {
			cleanPrompt := strings.ReplaceAll(step.Prompt, "\n", " ")
			if len(cleanPrompt) > 80 {
				cleanPrompt = cleanPrompt[:77] + "..."
			}
			action := "Normal Pass-through"
			if step.CanaryTripped || step.ToolTripped {
				action = "**TRIPWIRE ACTIVATED - Tarpit Engaged**"
			}
			sb.WriteString(fmt.Sprintf("| #%d | %s | `%s` | %s |\n", i+1, step.Timestamp.Format("15:04:05"), cleanPrompt, action))
		}
		sb.WriteString("\n")
	}

	sb.WriteString("## Containment Status\n\n")
	sb.WriteString("The session has been quarantined by honeyagent. All subsequent upstream queries are routed to synthetic hallucination generators, and all production database handles remain severed.\n")

	return sb.String()
}

// FormatIncidentSTIX exports an incident as a STIX 2.1 JSON bundle.
func FormatIncidentSTIX(inc *detector.Incident) ([]byte, error) {
	now := time.Now().UTC().Format(time.RFC3339Nano)

	incidentObj := map[string]interface{}{
		"type":        "incident",
		"spec_version": "2.1",
		"id":          fmt.Sprintf("incident--%s", inc.ID),
		"created":     inc.Timestamp.Format(time.RFC3339Nano),
		"modified":    now,
		"name":        inc.Title,
		"description": inc.Summary,
		"severity":    inc.Severity,
		"external_references": []map[string]string{
			{
				"source_name": "honeyagent-airlock",
				"external_id": inc.ID,
			},
		},
		"custom_properties": map[string]interface{}{
			"threat_score":      inc.ThreatScore,
			"mitre_atlas_ids":   inc.MITRETechniques,
			"client_ip":         inc.ClientIP,
			"trigger_type":      inc.TriggerType,
		},
	}

	indicatorObj := map[string]interface{}{
		"type":        "indicator",
		"spec_version": "2.1",
		"id":          fmt.Sprintf("indicator--%d", inc.Timestamp.UnixNano()),
		"created":     inc.Timestamp.Format(time.RFC3339Nano),
		"modified":    now,
		"name":        fmt.Sprintf("HoneyAgent %s Indicator", inc.TriggerType),
		"pattern":     fmt.Sprintf("[ipv4-addr:value = '%s']", inc.ClientIP),
		"pattern_type": "stix",
		"valid_from":  inc.Timestamp.Format(time.RFC3339Nano),
	}

	bundle := map[string]interface{}{
		"type":        "bundle",
		"id":          fmt.Sprintf("bundle--%s", inc.ID),
		"objects":     []interface{}{incidentObj, indicatorObj},
	}

	return json.MarshalIndent(bundle, "", "  ")
}
